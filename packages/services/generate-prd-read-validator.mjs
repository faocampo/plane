import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const Ajv = require("ajv/dist/2020");
const addFormats = require("ajv-formats");
const standaloneCode = require("ajv/dist/standalone");
const source = readFileSync(new URL("./src/curve/prd-review-context.schema.json", import.meta.url), "utf8");
const ajv = new Ajv({
  strict: true,
  allErrors: false,
  code: { source: true, esm: true },
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
});
addFormats(ajv);
let code = standaloneCode(ajv, ajv.compile(JSON.parse(source)));
// Static imports keep the browser runtime CSP-safe: no runtime schema compilation.
const imports = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_, path) => {
  if (!imports.has(path)) imports.set(path, `runtime${imports.size}`);
  return imports.get(path);
});
const header = `/**\n * Copyright (c) 2023-present Plane Software, Inc. and contributors\n * SPDX-License-Identifier: AGPL-3.0-only\n * Generated by generate-prd-read-validator.mjs; do not edit.\n * Schema SHA-256: ${createHash("sha256").update(source).digest("hex")}\n */\n`;
const output =
  header +
  [...imports]
    .map(
      ([path, name]) =>
        `import * as ${name}Module from "${path}.js";\nconst ${name} = ${name}Module.default && typeof ${name}Module.default === "object" ? ${name}Module.default : ${name}Module;\n`
    )
    .join("") +
  code +
  "\n";
writeFileSync(new URL("./src/curve/prd-review-context.validator.mjs", import.meta.url), output);
