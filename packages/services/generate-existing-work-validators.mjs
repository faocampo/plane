import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { format } from "oxfmt";
const require = createRequire(import.meta.url);
const Ajv = require("ajv/dist/2020");
const addFormats = require("ajv-formats");
const standaloneCode = require("ajv/dist/standalone");
const directory = new URL("./src/curve/existing-work-contracts/", import.meta.url);
const manifest = JSON.parse(readFileSync(new URL("manifest.json", directory), "utf8"));
const ajv = new Ajv({
  strict: true,
  allErrors: false,
  code: { source: true, esm: true },
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
});
addFormats(ajv);
const exports = {};
for (const entry of manifest) {
  const source = readFileSync(new URL(`${entry.name}.schema.json`, directory), "utf8");
  if (createHash("sha256").update(source).digest("hex") !== entry.sha256)
    throw new Error(`Schema pin mismatch: ${entry.name}`);
  const schema = JSON.parse(source);
  ajv.addSchema(schema);
  exports[`validate${entry.type}`] = schema.$id;
}
let code = standaloneCode(ajv, exports);
const imports = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_, path) => {
  if (!imports.has(path)) imports.set(path, `runtime${imports.size}`);
  return imports.get(path);
});
async function emit(filename, source) {
  // Reuse the repository's pinned formatter; generated output is deterministic and checkable.
  const formatted = await format(filename, source, { printWidth: 120, tabWidth: 2, trailingComma: "es5" });
  if (formatted.errors.length) throw new Error(`Generated output could not be formatted: ${filename}`);
  source = formatted.code;
  const destination = new URL(filename, directory);
  if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== source) throw new Error(`Generated output is stale: ${filename}`);
  } else {
    writeFileSync(destination, source);
  }
}
const header = `/**\n * Copyright (c) 2023-present Plane Software, Inc. and contributors\n * SPDX-License-Identifier: AGPL-3.0-only\n * Generated by generate-existing-work-validators.mjs; do not edit.\n */\n`;
await emit(
  "validators.mjs",
  header +
    [...imports]
      .map(
        ([path, name]) =>
          `import * as ${name}Module from "${path}.js";\nconst ${name} = ${name}Module.default && typeof ${name}Module.default === "object" ? ${name}Module.default : ${name}Module;\n`
      )
      .join("") +
    "/* oxlint-disable */\n" +
    code +
    "\n"
);
await emit(
  "validators.d.mts",
  header +
    `import type { ${manifest.map((entry) => entry.type).join(", ")} } from "@plane/types";\n` +
    manifest
      .map(
        (entry) =>
          `export declare const validate${entry.type}: { (input: unknown): input is ${entry.type}; errors?: unknown };\n`
      )
      .join("")
);
